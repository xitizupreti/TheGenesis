import type { Metadata } from "next";
import { band, members, socials } from "@/lib/band";
import type { Show } from "@/lib/shows";

// Canonical site URL. Set NEXT_PUBLIC_BASE_URL on Vercel when a custom domain
// is added; until then Vercel's production URL (or the default) is used.
export const SITE_URL = (
  process.env.NEXT_PUBLIC_BASE_URL ||
  (process.env.VERCEL_PROJECT_PRODUCTION_URL &&
    `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`) ||
  "https://thegenesis-ksus.vercel.app"
).replace(/\/+$/, "");

export const SITE_NAME = band.name;
export const DEFAULT_TITLE = `${band.name} — Women-Led Rock Band from Bhaktapur, Nepal`;
// Link-preview image (generated by `npm run brand-assets`). After replacing
// it, re-scrape at https://developers.facebook.com/tools/debug/ so Facebook,
// Instagram and WhatsApp drop their cached copy.
export const SHARE_IMAGE = {
  url: "/images/share.jpg",
  width: 1200,
  height: 630,
  type: "image/jpeg",
  alt: "The Genesis — women-led band from Bhaktapur, Nepal, performing live",
};

export const absoluteUrl = (path = "/") =>
  `${SITE_URL}${path === "/" ? "" : path}`;

export const sameAs = Object.values(socials)
  .map((s) => s.href)
  .filter(Boolean);

// Per-page metadata. Next.js replaces (not merges) openGraph/twitter objects
// from the layout — images included — so every page builds the full set here.
export function pageMetadata({
  title,
  description,
  path,
  image,
}: {
  title?: string;
  description: string;
  path: string;
  image?: { url: string; alt: string };
}): Metadata {
  const fullTitle = title ? `${title} — ${SITE_NAME}` : DEFAULT_TITLE;
  const images = [image ?? SHARE_IMAGE];
  return {
    ...(title && { title }),
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title: fullTitle,
      description,
      images,
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images,
    },
  };
}

// ---------- Structured data (JSON-LD) ----------

export function bandJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "MusicGroup",
    "@id": `${SITE_URL}/#band`,
    name: band.name,
    alternateName: ["The Genesis Band", "The Genesis Nepal"],
    slogan: band.shortTagline,
    url: SITE_URL,
    description: band.description,
    genre: ["Rock", "Metal", "Cover band"],
    image: [`${SITE_URL}/images/group.webp`, `${SITE_URL}/images/cover.webp`],
    logo: `${SITE_URL}/images/logo.webp`,
    ...(band.formedYear && { foundingDate: band.formedYear }),
    foundingLocation: {
      "@type": "Place",
      name: band.location,
      address: {
        "@type": "PostalAddress",
        addressLocality: "Bhaktapur",
        addressCountry: "NP",
      },
    },
    member: members.map((m) => ({
      "@type": "OrganizationRole",
      roleName: m.role,
      member: {
        "@type": "Person",
        name: m.name,
        image: `${SITE_URL}${m.photo}`,
        sameAs: [m.instagram],
      },
    })),
    sameAs,
  };
}

export function websiteJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": `${SITE_URL}/#website`,
    name: SITE_NAME,
    url: SITE_URL,
    inLanguage: "en",
    publisher: { "@id": `${SITE_URL}/#band` },
  };
}

export function eventsJsonLd(shows: Show[]) {
  return shows.map((s) => ({
    "@context": "https://schema.org",
    "@type": "MusicEvent",
    name: `${band.name} — ${s.title}`,
    startDate: s.date,
    eventStatus: "https://schema.org/EventScheduled",
    eventAttendanceMode: "https://schema.org/OfflineEventAttendanceMode",
    location: {
      "@type": "Place",
      name: s.venue,
      address: { "@type": "PostalAddress", addressLocality: s.city, addressCountry: "NP" },
    },
    image: [`${SITE_URL}${SHARE_IMAGE.url}`],
    description: s.note || `${band.name} live at ${s.venue}, ${s.city}.`,
    performer: { "@id": `${SITE_URL}/#band` },
    organizer: { "@id": `${SITE_URL}/#band` },
    ...(s.ticketUrl && {
      offers: { "@type": "Offer", url: s.ticketUrl, availability: "https://schema.org/InStock" },
    }),
  }));
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      item: absoluteUrl(item.path),
    })),
  };
}
